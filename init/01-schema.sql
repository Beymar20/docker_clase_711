CREATE TABLE ROL (
    COD_ROL VARCHAR(5) PRIMARY KEY,
    NOM_ROL VARCHAR(30) NOT NULL,
    DES_ROL VARCHAR(100)
);

CREATE TABLE EMPLEADO (
    CI_EMP VARCHAR(15) PRIMARY KEY,
    NOM_EMP VARCHAR(40) NOT NULL,
    APP_EMP VARCHAR(40) NOT NULL,
    APM_EMP VARCHAR(40),
    TEL_EMP BIGINT,
    COD_ROL_EMP VARCHAR(5),
    CONSTRAINT FK_EMP_ROL FOREIGN KEY (COD_ROL_EMP) REFERENCES ROL(COD_ROL)
);

CREATE TABLE HUESPED (
    DOC_HUE VARCHAR(15) PRIMARY KEY,
    NOM_HUE VARCHAR(40) NOT NULL,
    APP_HUE VARCHAR(40) NOT NULL,
    COR_HUE VARCHAR(60),
    TEL_HUE BIGINT,
    NAC_HUE VARCHAR(30)
);

CREATE TABLE HABITACION (
    NRO_HAB INT PRIMARY KEY,
    TIP_HAB VARCHAR(20) NOT NULL,
    CAP_HAB INT NOT NULL,
    EST_HAB VARCHAR(15) NOT NULL
);

CREATE TABLE RESERVA (
    COD_RES VARCHAR(8) PRIMARY KEY,
    DOC_HUE_RES VARCHAR(15) NOT NULL,
    NRO_HAB_RES INT NOT NULL,
    INI_RES DATE NOT NULL,
    FIN_RES DATE NOT NULL,
    QR_RES VARCHAR(255),
    CONSTRAINT FK_RES_HUE FOREIGN KEY (DOC_HUE_RES) REFERENCES HUESPED(DOC_HUE),
    CONSTRAINT FK_RES_HAB FOREIGN KEY (NRO_HAB_RES) REFERENCES HABITACION(NRO_HAB)
);

CREATE TABLE FORMULARIO_PRE_LLEGADA (
    COD_PRE VARCHAR(8) PRIMARY KEY,
    COD_RES_PRE VARCHAR(8) NOT NULL,
    ALE_PRE VARCHAR(100),
    MOT_PRE VARCHAR(100),
    PET_PRE VARCHAR(150),
    CONSTRAINT FK_PRE_RES FOREIGN KEY (COD_RES_PRE) REFERENCES RESERVA(COD_RES)
);

CREATE TABLE PLATILLO (
    COD_PLA VARCHAR(5) PRIMARY KEY,
    NOM_PLA VARCHAR(50) NOT NULL,
    PRE_PLA DECIMAL(8,2) NOT NULL,
    ACT_PLA VARCHAR(2) NOT NULL -- SI/NO
);

CREATE TABLE PEDIDO_KDS (
    COD_PED VARCHAR(8) PRIMARY KEY,
    COD_RES_PED VARCHAR(8) NOT NULL,
    FEC_PED DATE NOT NULL,
    HOR_PED TIME NOT NULL,
    EST_PED VARCHAR(20) NOT NULL,
    CONSTRAINT FK_PED_RES FOREIGN KEY (COD_RES_PED) REFERENCES RESERVA(COD_RES)
);

CREATE TABLE DETALLE_PEDIDO (
    COD_DET VARCHAR(8) PRIMARY KEY,
    COD_PED_DET VARCHAR(8) NOT NULL,
    COD_PLA_DET VARCHAR(5) NOT NULL,
    CAN_DET INT NOT NULL,
    CONSTRAINT FK_DET_PED FOREIGN KEY (COD_PED_DET) REFERENCES PEDIDO_KDS(COD_PED),
    CONSTRAINT FK_DET_PLA FOREIGN KEY (COD_PLA_DET) REFERENCES PLATILLO(COD_PLA)
);

CREATE TABLE PETICION_HOUSEKEEPING (
    COD_PHK VARCHAR(8) PRIMARY KEY,
    NRO_HAB_PHK INT NOT NULL,
    TIP_PHK VARCHAR(30) NOT NULL,
    EST_PHK VARCHAR(20) NOT NULL,
    HOR_PHK TIME NOT NULL,
    CONSTRAINT FK_PHK_HAB FOREIGN KEY (NRO_HAB_PHK) REFERENCES HABITACION(NRO_HAB)
);

CREATE TABLE TERAPEUTA (
    COD_TER VARCHAR(5) PRIMARY KEY,
    NOM_TER VARCHAR(40) NOT NULL,
    ESP_TER VARCHAR(50)
);

CREATE TABLE RESERVA_SPA (
    COD_RSP VARCHAR(8) PRIMARY KEY,
    DOC_HUE_RSP VARCHAR(15) NOT NULL,
    COD_TER_RSP VARCHAR(5) NOT NULL,
    FEC_RSP DATE NOT NULL,
    HOR_RSP TIME NOT NULL,
    CONSTRAINT FK_RSP_HUE FOREIGN KEY (DOC_HUE_RSP) REFERENCES HUESPED(DOC_HUE),
    CONSTRAINT FK_RSP_TER FOREIGN KEY (COD_TER_RSP) REFERENCES TERAPEUTA(COD_TER)
);

CREATE TABLE VEHICULO (
    PLA_VEH VARCHAR(10) PRIMARY KEY,
    CAP_VEH INT NOT NULL,
    EST_VEH VARCHAR(20) NOT NULL
);

CREATE TABLE ITINERARIO_TOUR (
    COD_ITI VARCHAR(8) PRIMARY KEY,
    DOC_HUE_ITI VARCHAR(15) NOT NULL,
    PLA_VEH_ITI VARCHAR(10) NOT NULL,
    CI_GUI_ITI VARCHAR(15) NOT NULL,
    FEC_ITI DATE NOT NULL,
    CLI_ITI VARCHAR(30),
    CONSTRAINT FK_ITI_HUE FOREIGN KEY (DOC_HUE_ITI) REFERENCES HUESPED(DOC_HUE),
    CONSTRAINT FK_ITI_VEH FOREIGN KEY (PLA_VEH_ITI) REFERENCES VEHICULO(PLA_VEH),
    CONSTRAINT FK_ITI_EMP FOREIGN KEY (CI_GUI_ITI) REFERENCES EMPLEADO(CI_EMP)
);

CREATE TABLE INSUMO (
    COD_INS VARCHAR(6) PRIMARY KEY,
    NOM_INS VARCHAR(50) NOT NULL,
    CAT_INS VARCHAR(30) NOT NULL,
    STO_INS INT NOT NULL
);

CREATE TABLE PARAMETROS_IO (
    COD_PIO VARCHAR(8) PRIMARY KEY,
    COD_INS_PIO VARCHAR(6) NOT NULL,
    EOQ_PIO DECIMAL(8,2),
    ROP_PIO DECIMAL(8,2),
    SEG_PIO DECIMAL(8,2),
    CONSTRAINT FK_PIO_INS FOREIGN KEY (COD_INS_PIO) REFERENCES INSUMO(COD_INS)
);